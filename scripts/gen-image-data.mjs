// One-off: turn scripts/_image-fetch-report.json into the typed
// src/data/architect-images.ts consumed by the architect detail pages.
// Re-run after fetch-architect-images.mjs to regenerate.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const report = JSON.parse(await readFile(path.join(ROOT, 'scripts/_image-fetch-report.json'), 'utf8'));

// Short courtesy names for firm-sourced images.
const FIRM = {
  'nick-deaver': 'Nick Deaver / Jes Deaver Architecture',
  'matt-fajkus': 'Matt Fajkus Architecture',
  'webber-studio': 'Webber + Studio',
  'a-parallel': 'A Parallel Architecture',
  pollen: 'Pollen Architecture & Design',
  'clayton-korte': 'Clayton Korte',
  'jay-corder': 'Jay Corder, Architect',
  'specht-novak': 'Specht Novak',
  'jay-hargrave': 'Jay Hargrave Architecture',
  'cuppett-kilpatrick': 'Cuppett Kilpatrick',
  'chioco-design': 'Chioco Design',
  alterstudio: 'Alterstudio Architecture',
  'furman-keil': 'Furman + Keil Architects',
  larue: 'LaRue Architects',
  'lake-flato': 'Lake|Flato Architects',
  'andersson-wise': 'Andersson-Wise Architects',
  'bercy-chen': 'Bercy Chen Studio',
  'michael-hsu': 'Michael Hsu Office of Architecture',
};

// Publication label for the "via" channel.
const VIA_LABEL = {
  ArchDaily: 'ArchDaily',
  Dezeen: 'Dezeen',
  Dwell: 'Dwell',
  designboom: 'designboom',
  HomeWorldDesign: 'HomeWorld Design',
  Archello: 'Archello',
};

function attribution(slug, img) {
  if (img.via === 'firm') return `Courtesy ${FIRM[slug]}`;
  const pub = VIA_LABEL[img.via] ?? img.via;
  return img.credit ? `Photo © ${img.credit} · via ${pub}` : `via ${pub}`;
}

function caption(img) {
  if (!img.project) return '';
  return img.year ? `${img.project} (${img.year})` : img.project;
}

const out = {};
for (const [slug, imgs] of Object.entries(report)) {
  if (!imgs.length) continue;
  out[slug] = imgs.map((img) => ({
    src: img.file, // e.g. images/architects/<slug>/1.jpg — prefix with link()
    width: img.width,
    height: img.height,
    caption: caption(img),
    attribution: attribution(slug, img),
    credit: img.credit ?? null,
    sourceUrl: img.sourcePage,
  }));
}

const header = `// AUTO-GENERATED by scripts/gen-image-data.mjs from scripts/_image-fetch-report.json.
// Do not edit by hand — re-run the fetch + gen scripts to regenerate.
// Signature project images for the architect detail-page galleries. Every image
// carries visible attribution (photographer where known, publication, and a
// link to the original source) per the project's licensing requirements.

export interface ArchitectImage {
  /** Path under public/, relative to the deploy base. Wrap with link(). */
  src: string;
  width: number;
  height: number;
  /** Project name + year, shown under the image. */
  caption: string;
  /** Ready-to-render credit line (photographer / courtesy / via publication). */
  attribution: string;
  /** Photographer, when known (null otherwise). */
  credit: string | null;
  /** Link to the original source page for the image. */
  sourceUrl: string;
}

export const architectImages: Record<string, ArchitectImage[]> = `;

const body = JSON.stringify(out, null, 2);
await writeFile(path.join(ROOT, 'src/data/architect-images.ts'), `${header}${body};\n`);
console.log(`Wrote src/data/architect-images.ts — ${Object.keys(out).length} firms, ${Object.values(out).reduce((s, a) => s + a.length, 0)} images.`);
